#!/usr/bin/env python3
"""Writes CREDITS.md from app/assets/ar/animals.json and tool/credits.json.

    python3 tool/make_credits.py

tool/credits.json holds, for each "<id>_photo" / "<id>_sound", the Wikimedia
Commons title, page, author and licence (filled in when a file is added).
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Where each model comes from (by file name in app/assets/ar/models).
MODELS = {
    "Fox.glb": ("Model by PixelMannen (CC0); rigging and animation by tomkranis; glTF conversion by @AsoboStudio "
                "and @scurest", "CC BY 4.0",
                "[Khronos glTF Sample Assets](https://github.com/KhronosGroup/glTF-Sample-Assets/tree/main/Models/Fox)"),
    "Horse.glb": ("mirada, from the ro.me project", "none stated (prototype only)",
                  "[three.js examples](https://github.com/mrdoob/three.js/tree/r160/examples/models/gltf)"),
    "Flamingo.glb": ("mirada, from the ro.me project", "none stated (prototype only)",
                     "[three.js examples](https://github.com/mrdoob/three.js/tree/r160/examples/models/gltf)"),
    "Parrot.glb": ("mirada, from the ro.me project", "none stated (prototype only)",
                   "[three.js examples](https://github.com/mrdoob/three.js/tree/r160/examples/models/gltf)"),
    "Stork.glb": ("mirada, from the ro.me project", "none stated (prototype only)",
                  "[three.js examples](https://github.com/mrdoob/three.js/tree/r160/examples/models/gltf)"),
}
POLY = "[Poly Pizza](https://poly.pizza/m/{})"
MODELS.update({
    "Lion.glb": ("Poly by Google", "CC BY 3.0", POLY.format("daMBBUnd9c9")),
    "Camel.glb": ("Poly by Google", "CC BY 3.0", POLY.format("7XeLogrxLad")),
    "Elephant.glb": ("elkiotbear", "CC BY 3.0", POLY.format("3AfO8NwcxD")),
    "Giraffe.glb": ("elkiotbear", "CC BY 3.0", POLY.format("gTFDiaGp8D")),
})
QUATERNIUS = ("Quaternius (Farm Animals pack), converted to GLB with tool/convert_models.py", "CC0 1.0",
              "[OpenGameArt](https://opengameart.org/node/85047)")


def main():
    animals = json.loads((ROOT / "app/assets/ar/animals.json").read_text())
    credits = json.loads((ROOT / "tool/credits.json").read_text())
    out = ["# Credits and licences", "",
           "Generated by `tool/make_credits.py`. **CC BY-SA** items need attribution, and copies or changes of",
           "them must keep the same licence. Keep this file with the app and show it on a Credits screen before",
           "publishing.", ""]

    def table(kind, title):
        out.extend([f"## {title}", "", "| Animal | Author | Licence | Source |", "|---|---|---|---|"])
        for a in animals:
            c = credits.get(f"{a['id']}_{kind}")
            if c:
                out.append(f"| {a['en']} | {c['artist']} | {c['license']} | [Wikimedia Commons]({c['page']}) |")
            elif kind == "sound":
                out.append(f"| {a['en']} | (no recording yet: the app says the name) | | |")
        out.append("")

    table("photo", "Photos (on the book pages)")
    table("sound", "Sounds (trimmed to a few seconds, volume levelled, AAC)")
    out.extend(["## 3D models", "", "| Animal | Author | Licence | Source |", "|---|---|---|---|"])
    for a in animals:
        model = Path(a["model"]).name
        who, lic, src = MODELS.get(model, QUATERNIUS)
        out.append(f"| {a['en']} | {who} | {lic} | {src} |")
    out += ["",
            "The horse, flamingo, parrot and stork from the three.js examples have no licence of their own. Fine for a",
            "prototype, but **replace them before publishing** (Quaternius has CC0 horses and birds).",
            "",
            "## Fonts", "",
            "- Poppins, by Indian Type Foundry and Jonny Pinhorn, SIL Open Font License 1.1 (`app/assets/fonts/OFL-Poppins.txt`)",
            "- Tajawal, by Boutros Fonts, SIL Open Font License 1.1 (`app/assets/fonts/OFL-Tajawal.txt`)",
            "",
            "## Libraries", "",
            "- MindAR 1.2.5, MIT, https://github.com/hiukim/mind-ar-js",
            "- three.js 0.160.0, MIT, https://github.com/mrdoob/three.js",
            "- flutter_inappwebview, Apache 2.0; permission_handler, MIT; shared_preferences, BSD-3-Clause;"
            " flutter_tts, MIT; gal, BSD-3-Clause",
            ""]
    (ROOT / "CREDITS.md").write_text("\n".join(out))
    print("wrote CREDITS.md")


if __name__ == "__main__":
    main()
